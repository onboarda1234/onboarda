"""Semantic guards for the customer-facing RegMind brand consolidation."""

import re
import zipfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
PORTAL = REPO_ROOT / "arie-portal.html"
BACKOFFICE = REPO_ROOT / "arie-backoffice.html"
MARKETING = REPO_ROOT / "index.html"
MARKETING_JSX = REPO_ROOT / "onboarda-website.jsx"
SERVER = REPO_ROOT / "arie-backend" / "server.py"

LEGACY_WORD = re.compile(r"\b(?:onboarda|arie)\b", re.IGNORECASE)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _legacy_lines(path: Path) -> list[str]:
    return [line.strip() for line in _read(path).splitlines() if LEGACY_WORD.search(line)]


